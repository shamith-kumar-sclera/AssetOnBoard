//
//  OUIDatabase.swift
//  AssetOnBoard
//
//  IEEE OUI prefix -> manufacturer lookup.
//
//  Stored as a packed string and parsed once on first use. A dictionary literal
//  of this size makes the Swift type checker crawl; a flat table costs a few
//  milliseconds at startup and compiles instantly.
//

import Foundation

nonisolated enum OUIDatabase {

    private static let table: [UInt32: String] = {
        var result: [UInt32: String] = [:]
        result.reserveCapacity(400)
        for line in packed.split(separator: "\n") {
            guard let separator = line.firstIndex(of: "=") else { continue }
            let prefix = line[line.startIndex..<separator]
            let vendor = String(line[line.index(after: separator)...])
            guard prefix.count == 6, let key = UInt32(prefix, radix: 16) else { continue }
            result[key] = vendor
        }
        return result
    }()

    /// Manufacturer registered to this address's OUI, if known.
    static func vendor(for mac: MACAddress) -> String? {
        // A self-assigned address carries no registry information at all.
        guard !mac.isLocallyAdministered else { return nil }
        return table[mac.oui]
    }

    static var count: Int { table.count }

